/**
 * 파일: backend/src/modules/organization/schema/orgSchema.ts
 * 역할: 조직도 관련 테이블(DEPARTMENTS, USERS) DDL 및 마이그레이션.
 *       서버 기동 시 initSchema.ts에서 호출 → 멱등(ORA-00955 무시).
 */

import { isAlreadyExists } from '../../../infra/oracle/errorCodes.js';

const DDL: string[] = [
  `
    CREATE TABLE DEPARTMENTS (
      DEPT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
      DEPT_NAME VARCHAR2(200 CHAR) NOT NULL,
      PARENT_DEPT_ID NUMBER NULL,
      SORT_ORDER NUMBER DEFAULT 0 NOT NULL,
      ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
      CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_DEPARTMENTS PRIMARY KEY (DEPT_ID),
      CONSTRAINT UK_DEPARTMENTS_NAME UNIQUE (DEPT_NAME),
      CONSTRAINT FK_DEPARTMENTS_PARENT FOREIGN KEY (PARENT_DEPT_ID) REFERENCES DEPARTMENTS(DEPT_ID)
    )
  `,
  `CREATE INDEX IDX_DEPARTMENTS_PARENT ON DEPARTMENTS (PARENT_DEPT_ID, SORT_ORDER)`,
  `
    CREATE TABLE POSITIONS (
      POSITION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
      POSITION_NAME VARCHAR2(100 CHAR) NOT NULL,
      SORT_ORDER NUMBER DEFAULT 0 NOT NULL,
      ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
      CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_POSITIONS PRIMARY KEY (POSITION_ID),
      CONSTRAINT UK_POSITIONS_NAME UNIQUE (POSITION_NAME)
    )
  `,
  `
    CREATE TABLE USERS (
      USER_ID NUMBER NOT NULL,
      USERNAME VARCHAR2(100 CHAR) NOT NULL,
      DISPLAY_NAME VARCHAR2(100 CHAR) NOT NULL,
      PASSWORD_HASH VARCHAR2(255 CHAR),
      ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
      DEPT_ID NUMBER NOT NULL,
      EMAIL VARCHAR2(200 CHAR),
      POSITION_NAME VARCHAR2(100 CHAR),
      POSITION_ID NUMBER,
      ADMIN_TYPE VARCHAR2(100 CHAR),
      USE_TYPE VARCHAR2(100 CHAR),
      RBAC_ROLE_ID VARCHAR2(50 CHAR),
      TELEGRAM_ID VARCHAR2(100 CHAR),
      CHECK_NOTICE NUMBER(1),
      CHECK_UPDATE NUMBER(1),
      SOURCE_CREATED_AT TIMESTAMP,
      SOURCE_UPDATED_AT TIMESTAMP,
      CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
      CONSTRAINT UK_USERS_USERNAME UNIQUE (USERNAME),
      CONSTRAINT FK_USERS_DEPT FOREIGN KEY (DEPT_ID) REFERENCES DEPARTMENTS(DEPT_ID),
      CONSTRAINT FK_USERS_POSITION FOREIGN KEY (POSITION_ID) REFERENCES POSITIONS(POSITION_ID)
    )
  `,
  `CREATE INDEX IDX_USERS_DEPT ON USERS (DEPT_ID, ENABLED)`,
  `CREATE INDEX IDX_USERS_POSITION ON USERS (POSITION_ID)`,
];

const MIGRATION_DDL: string[] = [
  `ALTER TABLE USERS ADD RBAC_ROLE_ID VARCHAR2(50 CHAR)`,
  `ALTER TABLE USERS ADD POSITION_ID NUMBER`,
  `ALTER TABLE USERS ADD CONSTRAINT FK_USERS_POSITION FOREIGN KEY (POSITION_ID) REFERENCES POSITIONS(POSITION_ID)`,
];

export async function ensureOrgSchema(connection: any): Promise<void> {
  for (const ddl of MIGRATION_DDL) {
    try { await connection.execute(ddl); } catch (_) {}
  }
  for (const ddl of DDL) {
    try { await connection.execute(ddl); }
    catch (error: any) { if (!isAlreadyExists(error)) throw error; }
  }
}
