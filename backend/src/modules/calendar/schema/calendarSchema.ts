import { isAlreadyExists } from '../../../infra/oracle/errorCodes.js';

const DDL = [
  `
    CREATE TABLE EVENTS (
      EVENT_ID    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
      TITLE       VARCHAR2(200 CHAR) NOT NULL,
      EVENT_TYPE  VARCHAR2(20 CHAR)  NOT NULL,
      CUSTOMER_ID NUMBER,
      SERVICE_NAME VARCHAR2(200 CHAR),
      START_AT    TIMESTAMP NOT NULL,
      END_AT      TIMESTAMP NOT NULL,
      METHOD      VARCHAR2(20 CHAR),
      MEMO        CLOB,
      CREATED_BY  NUMBER,
      ENABLED     NUMBER(1) DEFAULT 1 NOT NULL,
      CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      UPDATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_EVENTS PRIMARY KEY (EVENT_ID),
      CONSTRAINT FK_EVENTS_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(CUSTOMER_ID),
      CONSTRAINT FK_EVENTS_USER     FOREIGN KEY (CREATED_BY)  REFERENCES USERS(USER_ID)
    )
  `,
  `CREATE INDEX IDX_EVENTS_RANGE   ON EVENTS (START_AT, END_AT)`,
  `CREATE INDEX IDX_EVENTS_CUSTOMER ON EVENTS (CUSTOMER_ID)`,
  `
    CREATE TABLE EVENT_PARTICIPANTS (
      EVENT_ID NUMBER NOT NULL,
      USER_ID  NUMBER NOT NULL,
      ROLE     VARCHAR2(30 CHAR),
      CONSTRAINT PK_EVENT_PARTICIPANTS PRIMARY KEY (EVENT_ID, USER_ID),
      CONSTRAINT FK_EP_EVENT FOREIGN KEY (EVENT_ID) REFERENCES EVENTS(EVENT_ID) ON DELETE CASCADE,
      CONSTRAINT FK_EP_USER  FOREIGN KEY (USER_ID)  REFERENCES USERS(USER_ID)
    )
  `,
  `CREATE INDEX IDX_EP_USER ON EVENT_PARTICIPANTS (USER_ID)`,
  `
    CREATE TABLE ATTENDANCE_NOTICES (
      NOTICE_ID              VARCHAR2(40 CHAR) NOT NULL,
      STAFF_USER_ID          NUMBER NOT NULL,
      KIND                   VARCHAR2(20 CHAR) NOT NULL,
      ATTEND_DATE            DATE NOT NULL,
      EFFECTIVE_TIME         VARCHAR2(5 CHAR) NOT NULL,
      CUSTOMER_ID            NUMBER,
      SITE_NAME              VARCHAR2(200 CHAR),
      WORK_TITLE             VARCHAR2(200 CHAR),
      MEMO                   CLOB,
      MANUAL_LOCATION_TEXT   VARCHAR2(500 CHAR),
      GPS_LAT                NUMBER,
      GPS_LNG                NUMBER,
      GPS_ACCURACY           NUMBER,
      GPS_CAPTURED_AT        TIMESTAMP,
      GPS_CONSENT            NUMBER(1),
      STATUS                 VARCHAR2(30 CHAR) NOT NULL,
      MANAGER_USER_ID        NUMBER,
      MANAGER_SEEN_AT        TIMESTAMP,
      MANAGER_MEMO           CLOB,
      CREATED_AT             TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      UPDATED_AT             TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_ATTENDANCE_NOTICES PRIMARY KEY (NOTICE_ID),
      CONSTRAINT FK_AN_STAFF    FOREIGN KEY (STAFF_USER_ID) REFERENCES USERS(USER_ID),
      CONSTRAINT FK_AN_CUSTOMER FOREIGN KEY (CUSTOMER_ID)   REFERENCES CUSTOMERS(CUSTOMER_ID)
    )
  `,
  `CREATE INDEX IDX_AN_STAFF_DATE ON ATTENDANCE_NOTICES (STAFF_USER_ID, ATTEND_DATE)`,
  `ALTER TABLE EVENTS ADD ALL_DAY NUMBER(1) DEFAULT 0`,
  `ALTER TABLE EVENTS ADD COLOR VARCHAR2(20 CHAR)`,
  `ALTER TABLE EVENTS ADD LOCATION VARCHAR2(300 CHAR)`,
  `ALTER TABLE EVENTS ADD REMINDER_MINUTES NUMBER`,
  `ALTER TABLE EVENTS ADD RECURRENCE_RULE CLOB`,
  `ALTER TABLE EVENTS ADD RECURRENCE_EXDATES CLOB`,
  `ALTER TABLE EVENTS ADD RECURRENCE_MASTER_ID NUMBER`,
  `ALTER TABLE EVENTS ADD RECURRENCE_ORIGINAL_START TIMESTAMP`,
  `CREATE INDEX IDX_EVENTS_REC_MASTER ON EVENTS (RECURRENCE_MASTER_ID)`,
];

export async function ensureCalendarSchema(connection) {
  for (const ddl of DDL) {
    try { await connection.execute(ddl); }
    catch (err) { if (!isAlreadyExists(err)) throw err; }
  }
}
