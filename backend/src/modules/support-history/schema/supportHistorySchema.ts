import { isAlreadyExists } from '../../../infra/oracle/errorCodes.js';

const DDL = [
  `
    CREATE TABLE SUPPORT_HISTORIES (
      HISTORY_ID          VARCHAR2(20 CHAR)   NOT NULL,
      CUSTOMER_ID         NUMBER              NOT NULL,
      SERVICE_NAME        VARCHAR2(200 CHAR)  NOT NULL,
      HISTORY_TYPE        VARCHAR2(20 CHAR)   NOT NULL,
      SUPPORT_MODE        VARCHAR2(20 CHAR)   NOT NULL,
      STATUS              VARCHAR2(20 CHAR)   DEFAULT 'draft' NOT NULL,
      PRIORITY            VARCHAR2(10 CHAR)   DEFAULT 'p3' NOT NULL,
      DOCUMENT_KIND       VARCHAR2(30 CHAR),
      AI_CONFIDENCE       NUMBER,
      SUMMARY             VARCHAR2(1000 CHAR),
      WORK_DETAIL         CLOB,
      FINDING             CLOB,
      ACTION_RESULT       CLOB,
      PARSED_JSON         CLOB,
      DEPARTURE_AT        TIMESTAMP,
      SUPPORT_STARTED_AT  TIMESTAMP,
      SUPPORT_ENDED_AT    TIMESTAMP,
      RETURN_AT           TIMESTAMP,
      ENABLED             NUMBER(1)           DEFAULT 1 NOT NULL,
      CREATED_BY          NUMBER,
      CREATED_AT          TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
      UPDATED_AT          TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_SUPPORT_HISTORIES  PRIMARY KEY (HISTORY_ID),
      CONSTRAINT FK_SH_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(CUSTOMER_ID),
      CONSTRAINT FK_SH_USER     FOREIGN KEY (CREATED_BY)  REFERENCES USERS(USER_ID)
    )
  `,
  `CREATE INDEX IDX_SH_CUSTOMER ON SUPPORT_HISTORIES (CUSTOMER_ID)`,
  `CREATE INDEX IDX_SH_STARTED  ON SUPPORT_HISTORIES (SUPPORT_STARTED_AT)`,
  `CREATE INDEX IDX_SH_STATUS   ON SUPPORT_HISTORIES (STATUS, ENABLED)`,
  `ALTER TABLE SUPPORT_HISTORIES ADD DOCUMENT_KIND VARCHAR2(30 CHAR)`,
  `ALTER TABLE SUPPORT_HISTORIES ADD AI_CONFIDENCE NUMBER`,
  `ALTER TABLE SUPPORT_HISTORIES ADD PARSED_JSON CLOB`,
  `
    CREATE TABLE SUPPORT_HISTORY_PARTICIPANTS (
      PARTICIPANT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
      HISTORY_ID     VARCHAR2(20 CHAR) NOT NULL,
      USER_ID        NUMBER            NOT NULL,
      IS_MANAGER     NUMBER(1)         DEFAULT 0 NOT NULL,
      CONSTRAINT PK_SHP    PRIMARY KEY (PARTICIPANT_ID),
      CONSTRAINT UK_SHP    UNIQUE (HISTORY_ID, USER_ID),
      CONSTRAINT FK_SHP_HISTORY FOREIGN KEY (HISTORY_ID) REFERENCES SUPPORT_HISTORIES(HISTORY_ID) ON DELETE CASCADE,
      CONSTRAINT FK_SHP_USER    FOREIGN KEY (USER_ID)    REFERENCES USERS(USER_ID)
    )
  `,
  `CREATE INDEX IDX_SHP_USER ON SUPPORT_HISTORY_PARTICIPANTS (USER_ID)`,
];

export async function ensureSupportHistorySchema(connection) {
  for (const ddl of DDL) {
    try { await connection.execute(ddl); }
    catch (err) { if (!isAlreadyExists(err)) throw err; }
  }
}
