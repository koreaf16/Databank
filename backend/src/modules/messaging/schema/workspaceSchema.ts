/**
 * 파일: backend/src/modules/messaging/schema/workspaceSchema.ts
 * 역할: 채널 안 업무(workspace) 도입에 필요한 신규 테이블과 기존 테이블 ALTER를 한 곳에 모은다.
 *       messaging + support-history 양쪽에 걸쳐 FK가 형성되므로, 두 모듈 초기화 이후 마지막에 실행된다.
 *
 * 의존 객체 (먼저 존재해야 함):
 *   - CHANNELS, CHANNEL_SERVERS, CHANNEL_MESSAGES (messagingSchema)
 *   - SUPPORT_HISTORIES                          (supportHistorySchema)
 *   - USERS                                      (orgSchema)
 *
 * 신규 테이블:
 *   - CHANNEL_WORKSPACES       : 업무(시스템 단위 작업 공간) — 예: 계정계시스템, 홈페이지, MIS
 *   - CHANNEL_MESSAGE_TARGETS  : 메시지 ↔ 서버 N:M (비면 메시지는 "업무 전체" 대상)
 *   - SUPPORT_HISTORY_TARGETS  : 이력 ↔ 서버 N:M (비면 이력은 "업무 전체")
 *
 * 기존 테이블 ALTER (모두 nullable로 도입 → 기존 데이터/이력 깨짐 없음):
 *   - CHANNEL_SERVERS          : + WORKSPACE_ID (FK CHANNEL_WORKSPACES)
 *   - CHANNEL_MESSAGES         : + WORKSPACE_ID (FK CHANNEL_WORKSPACES)
 *   - SUPPORT_HISTORIES        : + WORKSPACE_ID (FK CHANNEL_WORKSPACES)
 *
 * 연관 파일:
 *   - server.ts                                   : 이 함수를 ensureMessagingSchema 뒤에 호출
 *   - repository/workspaceRepository.ts           : 업무 CRUD (후속 단계에서 추가)
 *   - repository/messageTargetRepository.ts       : 메시지-서버 N:M (후속)
 *   - support-history/repository/historyTargetRepository.ts : 이력-서버 N:M (후속)
 */

import { isAlreadyExists } from '../../../infra/oracle/errorCodes.js';

const DDL = [
  // 업무(workspace) — 시스템 단위 작업 공간 (예: 계정계시스템, 홈페이지, MIS)
  `CREATE TABLE CHANNEL_WORKSPACES (
     WORKSPACE_ID       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
     CHANNEL_ID         NUMBER             NOT NULL,
     NAME               VARCHAR2(200 CHAR) NOT NULL,
     STATUS             VARCHAR2(20 CHAR)  DEFAULT 'active' NOT NULL,
     PRIMARY_OWNER_ID   NUMBER,
     MEMO               VARCHAR2(1000 CHAR),
     ENABLED            NUMBER(1)          DEFAULT 1 NOT NULL,
     CREATED_BY         NUMBER,
     CREATED_AT         TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
     UPDATED_AT         TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
     CONSTRAINT PK_CHANNEL_WORKSPACES PRIMARY KEY (WORKSPACE_ID),
     CONSTRAINT FK_CW_CHANNEL FOREIGN KEY (CHANNEL_ID) REFERENCES CHANNELS(CHANNEL_ID) ON DELETE CASCADE,
     CONSTRAINT FK_CW_OWNER   FOREIGN KEY (PRIMARY_OWNER_ID) REFERENCES USERS(USER_ID),
     CONSTRAINT FK_CW_CREATOR FOREIGN KEY (CREATED_BY) REFERENCES USERS(USER_ID),
     CONSTRAINT UK_CW_CHANNEL_NAME UNIQUE (CHANNEL_ID, NAME)
   )`,
  `CREATE INDEX IDX_CW_CHANNEL ON CHANNEL_WORKSPACES (CHANNEL_ID, ENABLED)`,

  // 메시지 ↔ 서버 N:M 연결. 비면 메시지는 "업무 전체 대상".
  `CREATE TABLE CHANNEL_MESSAGE_TARGETS (
     MESSAGE_ID  NUMBER NOT NULL,
     SERVER_ID   NUMBER NOT NULL,
     CREATED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
     CONSTRAINT PK_CMT PRIMARY KEY (MESSAGE_ID, SERVER_ID),
     CONSTRAINT FK_CMT_MESSAGE FOREIGN KEY (MESSAGE_ID) REFERENCES CHANNEL_MESSAGES(MESSAGE_ID) ON DELETE CASCADE,
     CONSTRAINT FK_CMT_SERVER  FOREIGN KEY (SERVER_ID)  REFERENCES CHANNEL_SERVERS(CHANNEL_SERVER_ID) ON DELETE CASCADE
   )`,
  `CREATE INDEX IDX_CMT_SERVER ON CHANNEL_MESSAGE_TARGETS (SERVER_ID)`,

  // 이력 ↔ 서버 N:M 연결. 비면 이력은 "업무 전체 이력".
  `CREATE TABLE SUPPORT_HISTORY_TARGETS (
     HISTORY_ID VARCHAR2(20 CHAR) NOT NULL,
     SERVER_ID  NUMBER            NOT NULL,
     CREATED_AT TIMESTAMP         DEFAULT SYSTIMESTAMP NOT NULL,
     CONSTRAINT PK_SHT PRIMARY KEY (HISTORY_ID, SERVER_ID),
     CONSTRAINT FK_SHT_HISTORY FOREIGN KEY (HISTORY_ID) REFERENCES SUPPORT_HISTORIES(HISTORY_ID) ON DELETE CASCADE,
     CONSTRAINT FK_SHT_SERVER  FOREIGN KEY (SERVER_ID)  REFERENCES CHANNEL_SERVERS(CHANNEL_SERVER_ID) ON DELETE CASCADE
   )`,
  `CREATE INDEX IDX_SHT_SERVER ON SUPPORT_HISTORY_TARGETS (SERVER_ID)`,

  // ── 기존 테이블 컬럼 추가 (모두 nullable로 도입) ────────────────────────────
  `ALTER TABLE CHANNEL_SERVERS  ADD (WORKSPACE_ID NUMBER)`,
  `ALTER TABLE CHANNEL_SERVERS  ADD CONSTRAINT FK_CS_WORKSPACE
     FOREIGN KEY (WORKSPACE_ID) REFERENCES CHANNEL_WORKSPACES(WORKSPACE_ID)`,
  `CREATE INDEX IDX_CS_WORKSPACE ON CHANNEL_SERVERS (WORKSPACE_ID)`,

  `ALTER TABLE CHANNEL_MESSAGES ADD (WORKSPACE_ID NUMBER)`,
  `ALTER TABLE CHANNEL_MESSAGES ADD CONSTRAINT FK_MSG_WORKSPACE
     FOREIGN KEY (WORKSPACE_ID) REFERENCES CHANNEL_WORKSPACES(WORKSPACE_ID)`,
  `CREATE INDEX IDX_MSG_WORKSPACE ON CHANNEL_MESSAGES (WORKSPACE_ID)`,

  `ALTER TABLE SUPPORT_HISTORIES ADD (WORKSPACE_ID NUMBER)`,
  `ALTER TABLE SUPPORT_HISTORIES ADD CONSTRAINT FK_SH_WORKSPACE
     FOREIGN KEY (WORKSPACE_ID) REFERENCES CHANNEL_WORKSPACES(WORKSPACE_ID)`,
  `CREATE INDEX IDX_SH_WORKSPACE ON SUPPORT_HISTORIES (WORKSPACE_ID)`,

  // 부 엔지니어(부 담당자) 컬럼 — 정 엔지니어와 페어로 업무에 배정
  `ALTER TABLE CHANNEL_WORKSPACES ADD (SECONDARY_OWNER_ID NUMBER)`,
  `ALTER TABLE CHANNEL_WORKSPACES ADD CONSTRAINT FK_CW_SEC_OWNER
     FOREIGN KEY (SECONDARY_OWNER_ID) REFERENCES USERS(USER_ID)`,
];

export async function ensureWorkspaceSchema(connection: any) {
  for (const ddl of DDL) {
    try { await connection.execute(ddl); }
    catch (err) { if (!isAlreadyExists(err)) throw err; }
  }
}
