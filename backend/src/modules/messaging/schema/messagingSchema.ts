import { isAlreadyExists } from '../../../infra/oracle/errorCodes.js';

const DDL = [
  // 채널 — kind: customer / team / incident / announcement / dm
  `CREATE TABLE CHANNELS (
     CHANNEL_ID    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
     KIND          VARCHAR2(20 CHAR)  NOT NULL,
     NAME          VARCHAR2(200 CHAR) NOT NULL,
     TOPIC         VARCHAR2(500 CHAR),
     CUSTOMER_ID   NUMBER,
     DEPT_ID       NUMBER,
     SEVERITY      VARCHAR2(10 CHAR),
     STATUS        VARCHAR2(20 CHAR)  DEFAULT 'active'  NOT NULL,
     IS_PINNED     NUMBER(1)          DEFAULT 0          NOT NULL,
     IS_READ_ONLY  NUMBER(1)          DEFAULT 0          NOT NULL,
     ICON          VARCHAR2(50 CHAR),
     COLOR         VARCHAR2(20 CHAR),
     CREATED_BY    NUMBER,
     CREATED_AT    TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
     UPDATED_AT    TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
     CONSTRAINT PK_CHANNELS          PRIMARY KEY (CHANNEL_ID),
     CONSTRAINT FK_CHANNELS_CUSTOMER  FOREIGN KEY (CUSTOMER_ID)  REFERENCES CUSTOMERS(CUSTOMER_ID),
     CONSTRAINT FK_CHANNELS_DEPT      FOREIGN KEY (DEPT_ID)       REFERENCES DEPARTMENTS(DEPT_ID),
     CONSTRAINT FK_CHANNELS_CREATOR   FOREIGN KEY (CREATED_BY)    REFERENCES USERS(USER_ID)
   )`,
  `CREATE INDEX IDX_CHANNELS_KIND       ON CHANNELS (KIND, STATUS)`,
  `CREATE INDEX IDX_CHANNELS_CUSTOMER   ON CHANNELS (CUSTOMER_ID)`,
  `CREATE INDEX IDX_CHANNELS_DEPT       ON CHANNELS (DEPT_ID)`,

  // 채널 멤버 (구독자)
  `CREATE TABLE CHANNEL_MEMBERS (
     CHANNEL_ID  NUMBER NOT NULL,
     USER_ID     NUMBER NOT NULL,
     JOINED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
     CONSTRAINT PK_CHANNEL_MEMBERS  PRIMARY KEY (CHANNEL_ID, USER_ID),
     CONSTRAINT FK_CM_CHANNEL        FOREIGN KEY (CHANNEL_ID) REFERENCES CHANNELS(CHANNEL_ID) ON DELETE CASCADE,
     CONSTRAINT FK_CM_USER           FOREIGN KEY (USER_ID)    REFERENCES USERS(USER_ID)
   )`,

  // 채널 안 서버 목록. 이 설계에서는 서버가 업무 단위이며, 서버별 정/부 엔지니어를 지정한다.
  `CREATE TABLE CHANNEL_SERVERS (
     CHANNEL_SERVER_ID     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
     CHANNEL_ID            NUMBER             NOT NULL,
     SERVER_NAME           VARCHAR2(200 CHAR) NOT NULL,
     PLATFORM              VARCHAR2(100 CHAR),
     PRODUCT_NAME          VARCHAR2(100 CHAR) NOT NULL,
     STATUS                VARCHAR2(20 CHAR)  DEFAULT 'active' NOT NULL,
     PRIMARY_ENGINEER_ID   NUMBER,
     SECONDARY_ENGINEER_ID NUMBER,
     MEMO                  VARCHAR2(1000 CHAR),
     ENABLED               NUMBER(1)          DEFAULT 1 NOT NULL,
     CREATED_BY            NUMBER,
     CREATED_AT            TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
     UPDATED_AT            TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
     CONSTRAINT PK_CHANNEL_SERVERS PRIMARY KEY (CHANNEL_SERVER_ID),
     CONSTRAINT FK_CS_CHANNEL FOREIGN KEY (CHANNEL_ID) REFERENCES CHANNELS(CHANNEL_ID) ON DELETE CASCADE,
     CONSTRAINT FK_CS_PRIMARY_ENGINEER FOREIGN KEY (PRIMARY_ENGINEER_ID) REFERENCES USERS(USER_ID),
     CONSTRAINT FK_CS_SECONDARY_ENGINEER FOREIGN KEY (SECONDARY_ENGINEER_ID) REFERENCES USERS(USER_ID),
     CONSTRAINT FK_CS_CREATOR FOREIGN KEY (CREATED_BY) REFERENCES USERS(USER_ID),
     CONSTRAINT CK_CS_ENGINEER_PAIR CHECK (
       PRIMARY_ENGINEER_ID IS NULL OR SECONDARY_ENGINEER_ID IS NULL OR PRIMARY_ENGINEER_ID <> SECONDARY_ENGINEER_ID
     )
   )`,
  `CREATE INDEX IDX_CS_CHANNEL ON CHANNEL_SERVERS (CHANNEL_ID, ENABLED)`,
  `CREATE INDEX IDX_CS_PRIMARY_ENGINEER ON CHANNEL_SERVERS (PRIMARY_ENGINEER_ID, ENABLED)`,
  `CREATE INDEX IDX_CS_SECONDARY_ENGINEER ON CHANNEL_SERVERS (SECONDARY_ENGINEER_ID, ENABLED)`,

  // 메시지
  `CREATE TABLE CHANNEL_MESSAGES (
     MESSAGE_ID    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
     CHANNEL_ID    NUMBER             NOT NULL,
     AUTHOR_USER_ID NUMBER,
     IS_BOT        NUMBER(1)          DEFAULT 0  NOT NULL,
     BOT_NAME      VARCHAR2(100 CHAR),
     MSG_TYPE      VARCHAR2(20 CHAR)  DEFAULT 'text' NOT NULL,
     CONTENT       CLOB,
     ATTACHMENT_JSON CLOB,
     PARENT_ID     NUMBER,
     THREAD_COUNT  NUMBER             DEFAULT 0  NOT NULL,
     ENABLED       NUMBER(1)          DEFAULT 1  NOT NULL,
     SENT_AT       TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
     UPDATED_AT    TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
     CONSTRAINT PK_CHANNEL_MESSAGES   PRIMARY KEY (MESSAGE_ID),
     CONSTRAINT FK_MSG_CHANNEL         FOREIGN KEY (CHANNEL_ID)     REFERENCES CHANNELS(CHANNEL_ID) ON DELETE CASCADE,
     CONSTRAINT FK_MSG_AUTHOR          FOREIGN KEY (AUTHOR_USER_ID) REFERENCES USERS(USER_ID),
     CONSTRAINT FK_MSG_PARENT          FOREIGN KEY (PARENT_ID)      REFERENCES CHANNEL_MESSAGES(MESSAGE_ID)
   )`,
  `CREATE INDEX IDX_MSG_CHANNEL_TIME ON CHANNEL_MESSAGES (CHANNEL_ID, SENT_AT DESC)`,
  `CREATE INDEX IDX_MSG_PARENT       ON CHANNEL_MESSAGES (PARENT_ID)`,

  // 메시지 리액션
  `CREATE TABLE MESSAGE_REACTIONS (
     MESSAGE_ID  NUMBER            NOT NULL,
     USER_ID     NUMBER            NOT NULL,
     EMOJI       VARCHAR2(20 CHAR) NOT NULL,
     REACTED_AT  TIMESTAMP         DEFAULT SYSTIMESTAMP NOT NULL,
     CONSTRAINT PK_MSG_REACTIONS  PRIMARY KEY (MESSAGE_ID, USER_ID, EMOJI),
     CONSTRAINT FK_MR_MESSAGE     FOREIGN KEY (MESSAGE_ID) REFERENCES CHANNEL_MESSAGES(MESSAGE_ID) ON DELETE CASCADE,
     CONSTRAINT FK_MR_USER        FOREIGN KEY (USER_ID)    REFERENCES USERS(USER_ID)
   )`,
  `CREATE INDEX IDX_MR_MESSAGE ON MESSAGE_REACTIONS (MESSAGE_ID)`,
];

export async function ensureMessagingSchema(connection) {
  for (const ddl of DDL) {
    try { await connection.execute(ddl); }
    catch (err) { if (!isAlreadyExists(err)) throw err; }
  }
  await seedDepartmentChannels(connection);
}

async function seedDepartmentChannels(connection) {
  await connection.execute(`
    INSERT INTO CHANNELS (
      KIND, NAME, TOPIC, CUSTOMER_ID, DEPT_ID,
      SEVERITY, STATUS, IS_PINNED, IS_READ_ONLY, ICON, COLOR, CREATED_BY,
      CREATED_AT, UPDATED_AT
    )
    SELECT
      'team',
      d.DEPT_NAME || '-공용',
      '부서 공용 채널',
      NULL,
      d.DEPT_ID,
      NULL,
      'active',
      0,
      0,
      NULL,
      '#667085',
      NULL,
      SYSTIMESTAMP,
      SYSTIMESTAMP
    FROM DEPARTMENTS d
    WHERE d.ENABLED = 1
      AND NOT EXISTS (
        SELECT 1
        FROM CHANNELS c
        WHERE c.KIND = 'team'
          AND c.DEPT_ID = d.DEPT_ID
          AND c.STATUS = 'active'
      )
  `);

  await connection.execute(`
    INSERT INTO CHANNEL_MEMBERS (CHANNEL_ID, USER_ID)
    SELECT c.CHANNEL_ID, u.USER_ID
    FROM CHANNELS c
    JOIN USERS u ON u.DEPT_ID = c.DEPT_ID AND u.ENABLED = 1
    WHERE c.KIND = 'team'
      AND c.STATUS = 'active'
      AND c.DEPT_ID IS NOT NULL
      AND NOT EXISTS (
        SELECT 1
        FROM CHANNEL_MEMBERS cm
        WHERE cm.CHANNEL_ID = c.CHANNEL_ID
          AND cm.USER_ID = u.USER_ID
      )
  `);
}
